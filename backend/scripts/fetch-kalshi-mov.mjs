// Fetch Kalshi margin-of-victory markets (KXMIDTERMMOV-*) for NC federal races
// and write a SQL file that updates public.markets with the derived predicted
// margin (median interpolation of the threshold ladder).
//
// Run: node backend/scripts/fetch-kalshi-mov.mjs
// Output: kalshi-mov-load.sql  (human-run against Supabase)
import { writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..', '..');
const BASE = 'https://api.elections.kalshi.com/trade-api/v2';
const CYCLE = '2026';

// race_id -> [D event, R event]
const RACES = {
  'NC-SEN': ['KXMIDTERMMOV-NCSEND', 'KXMIDTERMMOV-NCSENR'],
  'NC-01': ['KXMIDTERMMOV-NC01D', 'KXMIDTERMMOV-NC01R'],
  'NC-02': ['KXMIDTERMMOV-NC02D', 'KXMIDTERMMOV-NC02R'],
  'NC-03': ['KXMIDTERMMOV-NC03D', 'KXMIDTERMMOV-NC03R'],
  'NC-04': ['KXMIDTERMMOV-NC04D', 'KXMIDTERMMOV-NC04R'],
  'NC-05': ['KXMIDTERMMOV-NC05D', 'KXMIDTERMMOV-NC05R'],
  'NC-06': ['KXMIDTERMMOV-NC06D', 'KXMIDTERMMOV-NC06R'],
  'NC-07': ['KXMIDTERMMOV-NC07D', 'KXMIDTERMMOV-NC07R'],
  'NC-08': ['KXMIDTERMMOV-NC08D', 'KXMIDTERMMOV-NC08R'],
  'NC-09': ['KXMIDTERMMOV-NC09D', 'KXMIDTERMMOV-NC09R'],
  'NC-10': ['KXMIDTERMMOV-NC10D', 'KXMIDTERMMOV-NC10R'],
  'NC-11': ['KXMIDTERMMOV-NC11D', 'KXMIDTERMMOV-NC11R'],
  'NC-12': ['KXMIDTERMMOV-NC12D', 'KXMIDTERMMOV-NC12R'],
  'NC-13': ['KXMIDTERMMOV-NC13D', 'KXMIDTERMMOV-NC13R'],
  'NC-14': ['KXMIDTERMMOV-NC14D', 'KXMIDTERMMOV-NC14R'],
};

async function fetchEvent(event) {
  const url = `${BASE}/markets?event_ticker=${event}&limit=200`;
  const res = await fetch(url, { headers: { Accept: 'application/json' } });
  if (!res.ok) throw new Error(`http ${res.status} for ${event}`);
  const d = await res.json();
  const pts = [];
  for (const m of (d.markets || [])) {
    const mm = m.ticker.match(/-P(\d+)$/);
    if (!mm) continue;
    const x = parseInt(mm[1], 10);
    // Prefer the traded price; fall back to the live bid when there is no trade
    // (last_price_dollars is 0 for untraded contracts, which would otherwise
    // drop a heavily-favoured race to a false EVEN).
    const last = parseFloat(m.last_price_dollars ?? 0);
    const bid = parseFloat(m.yes_bid_dollars ?? 0);
    const price = last > 0 ? last : bid;
    pts.push({ x, price });
  }
  pts.sort((a, b) => a.x - b.x);
  return pts;
}

// Derive the median margin (X where P(margin >= X) = 0.5) from a threshold ladder.
function medianMargin(pts) {
  if (pts.length < 2) return null;
  let lo = null, hi = null;
  for (let i = 0; i < pts.length; i++) {
    if (pts[i].price >= 0.5) lo = pts[i];
    else { hi = pts[i]; break; }
  }
  if (!lo) return null;
  if (!hi) return lo.x;
  const pLo = lo.price, pHi = hi.price;
  if (pLo === pHi) return lo.x;
  const frac = (pLo - 0.5) / (pLo - pHi);
  return lo.x + frac * (hi.x - lo.x);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const lines = [];
lines.push('-- Margin-of-victory load for Kalshi MOV markets.');
lines.push('-- Generated by fetch-kalshi-mov.mjs. Human-run against Supabase.');
lines.push('begin;');
for (const [race, [evD, evR]] of Object.entries(RACES)) {
  await sleep(200);
  let ptsD = [], ptsR = [];
  try { ptsD = await fetchEvent(evD); } catch (e) { console.error(race, evD, e.message); }
  await sleep(200);
  try { ptsR = await fetchEvent(evR); } catch (e) { console.error(race, evR, e.message); }
  const mD = medianMargin(ptsD);
  const mR = medianMargin(ptsR);
  const dFavored = ptsD.length && ptsD[0].price > 0.5;
  const rFavored = ptsR.length && ptsR[0].price > 0.5;
  let party = 'EVEN', margin = 0;
  if (dFavored && rFavored) {
    if ((mD ?? 0) >= (mR ?? 0)) { party = 'D'; margin = mD; }
    else { party = 'R'; margin = mR; }
  } else if (dFavored) { party = 'D'; margin = mD; }
  else if (rFavored) { party = 'R'; margin = mR; }
  const m = Math.round(margin * 10) / 10;
  lines.push(`update public.markets set mov_party='${party}', mov_margin=${m}, mov_updated_at=now() where race_id='${race}' and cycle='${CYCLE}' and provider='Kalshi';`);
  console.log(`${race}: ${party} +${m}`);
}
lines.push('commit;');
writeFileSync(join(REPO, 'kalshi-mov-load.sql'), lines.join('\n') + '\n');
console.log('wrote kalshi-mov-load.sql');